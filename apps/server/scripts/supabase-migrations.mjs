// Brings the database schema the Nuvio server runs on into migrations/:
//
// - migrations/0001_gotrue.sql: Supabase Auth's (GoTrue's) own migrations,
//   from references/gotrue/migrations, rendered for the "auth" schema, as
//   GoTrue renders them when it starts.
// - migrations/nuvio/*.sql: Nuvio's migrations, copied unchanged from
//   references/self-host/database/migrations.
//
// `--check` fails when the files here differ from what the references give,
// and is quiet when the references aren't checked out (CI).
//
// Usage: node scripts/supabase-migrations.mjs [--check]

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const server = join(here, "..");
const references = join(server, "..", "..", "references");
const gotrueDir = join(references, "gotrue", "migrations");
const nuvioDir = join(references, "self-host", "database", "migrations");
const check = process.argv.includes("--check");

if (!existsSync(gotrueDir) || !existsSync(nuvioDir)) {
  if (check) process.exit(0);
  console.error("references/gotrue and references/self-host must be checked out (see references/README.md)");
  process.exit(1);
}

const wanted = new Map();

// GoTrue: every *.up.sql in name order (pop runs "x.postgres.up.sql" on Postgres).
const gotrue = readdirSync(gotrueDir)
  .filter(name => name.endsWith(".up.sql"))
  .toSorted();
let rendered =
  "-- Generated by scripts/supabase-migrations.mjs from Supabase Auth v2.189.0's\n" +
  "-- migrations (references/gotrue). Don't edit; run the script again.\n\n";
for (const name of gotrue) {
  const version = name.split("_")[0];
  const sql = readFileSync(join(gotrueDir, name), "utf8").replace(
    /\{\{\s*index \.Options "Namespace"\s*\}\}/g,
    "auth",
  );
  const body = sql.trim();
  rendered += `-- ${name}\n${body}${body.endsWith(";") ? "" : ";"}\n`;
  rendered += `INSERT INTO auth.schema_migrations (version) VALUES ('${version}') ON CONFLICT DO NOTHING;\n\n`;
}
wanted.set(join(server, "migrations", "0001_gotrue.sql"), rendered);

for (const name of readdirSync(nuvioDir)
  .filter(n => n.endsWith(".sql"))
  .toSorted()) {
  wanted.set(join(server, "migrations", "nuvio", name), readFileSync(join(nuvioDir, name), "utf8"));
}

let differs = 0;
for (const [path, text] of wanted) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === text) continue;
  if (check) {
    console.error(`${path} differs from the references; run node scripts/supabase-migrations.mjs`);
    differs++;
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote ${path}`);
  }
}
if (differs) process.exit(1);
